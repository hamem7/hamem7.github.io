// 🌟 العبارة كما في مصحف المنصة (بتشكيله)، أو null إن لم توجد في نص الآية المعطى
export function pairPhrase(rawAyahText, pair) {
    const ayahText = withoutWaqf(rawAyahText);
    const ranges = findPhraseRanges(ayahText, pair.h);
    return ranges && ranges.length ? ayahText.slice(ranges[0][0], ranges[0][1]) : null;
}
