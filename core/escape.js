// 🌟🌟 [جديد] دالة تنظيف موحَّدة لأي نص قادم من خارج جهاز المعلم (اسم الطالب، إجاباته، نصوص الأسئلة من الخادم)
// قبل حقنه في innerHTML. سبب الإضافة (تدقيق ما قبل الإطلاق 2026-09-29): كان اسم الطالب وإجاباته يُعرضان
// للمعلم بلا تنظيف، فيستطيع أي طالب يملك رابط الواجب تنفيذ كود داخل جلسة المعلم (XSS مخزَّنة).
export function esc(s) {
    return String(s == null ? '' : s).replace(/[&<>"'`]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;', '`': '&#96;' }[c]));
}
