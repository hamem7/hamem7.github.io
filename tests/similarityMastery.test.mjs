// tests/similarityMastery.test.mjs — node tests/similarityMastery.test.mjs
import assert from 'node:assert/strict';
import { groupSignature, createEmptyProgress, applyRoundToProgress, levelOf, isDue, summarizeProgress, groupAnswersBySignature, summarizeByType, BOX_INTERVAL_DAYS } from '../engine/similarityMastery.js';
const D = 86400000, T0 = 1_700_000_000_000;
const g = { scope: 'internal', surahs: [2], occurrences: [{ ayahNumber: 17 }, { ayahNumber: 5 }, { ayahNumber: 17 }] };
assert.equal(groupSignature(g), '2:5,17');
assert.equal(groupSignature({ scope: 'juzAmma', occurrences: [{ surahNumber: 85, ayahRange: '17' }, { surahNumber: 79, ayahRange: '15' }] }), 'amma:79-15,85-17');
let r = createEmptyProgress(1, '2:5,17');
assert.equal(levelOf(r, T0), 'new');
const ok = [{ isCorrect: true, type: 'sim_position' }, { isCorrect: true, type: 'sim_recall' }];
const bad = [{ isCorrect: true, type: 'sim_position' }, { isCorrect: false, type: 'sim_recall' }];
r = applyRoundToProgress(r, ok, T0);
assert.deepEqual([r.box, r.streak, r.attempts, r.correct, r.rounds], [1, 1, 2, 2, 1]);
assert.equal(levelOf(r, T0), 'learning');
assert.equal(r.dueAt, T0 + BOX_INTERVAL_DAYS[1] * D);
for (let i = 0; i < 3; i++) r = applyRoundToProgress(r, ok, T0);
assert.equal(r.box, 4); assert.equal(levelOf(r, T0), 'mastered');
assert.equal(levelOf(r, T0 + 15 * D), 'review'); assert.ok(isDue(r, T0 + 15 * D)); assert.ok(!isDue(r, T0));
r = applyRoundToProgress(r, bad, T0);
assert.equal(r.box, 2); assert.equal(r.streak, 0); assert.equal(levelOf(r, T0), 'improving');
r = applyRoundToProgress(r, bad, T0); r = applyRoundToProgress(r, bad, T0);
assert.equal(r.box, 0);
r = applyRoundToProgress(r, ok, T0); r = applyRoundToProgress(r, ok, T0); r = applyRoundToProgress(r, ok, T0);
r = applyRoundToProgress(r, ok, T0); r = applyRoundToProgress(r, ok, T0); r = applyRoundToProgress(r, ok, T0);
assert.equal(r.box, 5, 'capped at MAX_BOX');
assert.equal(applyRoundToProgress(r, [], T0).rounds, r.rounds);
const s = summarizeProgress([r, createEmptyProgress(1, 'x')], T0);
assert.equal(s.total, 2); assert.equal(s.mastered, 1);
const ans = [{ sig: 'a', type: 't1', isCorrect: true }, { sig: 'a', type: 't2', isCorrect: false }, { sig: 'b', type: 't1', isCorrect: true }];
assert.equal(groupAnswersBySignature(ans).length, 2);
assert.deepEqual(summarizeByType(ans), { t1: { n: 2, c: 2 }, t2: { n: 1, c: 0 } });
console.log('similarityMastery: all assertions passed');
